use std::collections::BTreeMap;
use std::error::Error;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

mod inventory;
mod smoke_kind;

const BUNDLE: &str = "spec/openapi/api.github.com.json";
const OUTPUT: &str = "crates/spec/src/ops_gen.rs";
const SLASH_PARAMS: [&str; 6] = ["ref", "path", "branch", "basehead", "tag", "tree_sha"];
const METHODS: [(&str, &str); 5] = [
    ("get", "Get"),
    ("post", "Post"),
    ("put", "Put"),
    ("patch", "Patch"),
    ("delete", "Delete"),
];

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args.as_slice() {
        [task] if task == "gen" => generate(&root()),
        [task, rest @ ..] if task == "inventory" => inventory::run(&root(), rest),
        [task] if task == "smoke-kind" => smoke_kind::run(&root()),
        _ => Err(
            "usage: xtask gen | xtask inventory --client <path> [--check] | xtask smoke-kind"
                .into(),
        ),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("xtask: {e}");
            ExitCode::FAILURE
        }
    }
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map_or_else(|| PathBuf::from("."), Path::to_path_buf)
}

struct Op {
    id: String,
    method: usize,
    path: String,
    category: String,
    subcategory: String,
}

#[derive(Default)]
struct Node {
    literals: BTreeMap<String, usize>,
    param: Option<usize>,
    rest: Option<usize>,
    ops: Vec<(usize, usize)>,
}

fn generate(root: &Path) -> Result<(), Box<dyn Error>> {
    let bundle: serde_json::Value = serde_json::from_slice(&std::fs::read(root.join(BUNDLE))?)?;
    let ops = operations(&bundle)?;
    let nodes = tree(&ops)?;
    std::fs::write(root.join(OUTPUT), render(&ops, &nodes)?)?;
    eprintln!(
        "xtask: wrote {OUTPUT}: {} operations, {} nodes",
        ops.len(),
        nodes.len()
    );
    Ok(())
}

fn operations(bundle: &serde_json::Value) -> Result<Vec<Op>, Box<dyn Error>> {
    let paths = bundle["paths"]
        .as_object()
        .ok_or("the bundle has no paths")?;
    let mut ops = Vec::new();
    for (path, item) in paths {
        for (method, (key, _)) in METHODS.iter().enumerate() {
            let Some(op) = item.get(*key) else { continue };
            let id = op["operationId"]
                .as_str()
                .ok_or_else(|| format!("{key} {path} has no operationId"))?;
            let text = |field: &str| {
                op["x-github"][field]
                    .as_str()
                    .unwrap_or_default()
                    .to_owned()
            };
            ops.push(Op {
                id: id.to_owned(),
                method,
                path: path.clone(),
                category: text("category"),
                subcategory: text("subcategory"),
            });
        }
    }
    ops.sort_by(|a, b| (&a.path, a.method).cmp(&(&b.path, b.method)));
    Ok(ops)
}

fn tree(ops: &[Op]) -> Result<Vec<Node>, Box<dyn Error>> {
    let mut nodes = vec![Node::default()];
    for (index, op) in ops.iter().enumerate() {
        let mut at = 0;
        for segment in op.path.trim_start_matches('/').split('/') {
            let next = nodes.len();
            let child = match segment.strip_prefix('{').and_then(|s| s.strip_suffix('}')) {
                Some(name) if SLASH_PARAMS.contains(&name) => nodes[at].rest.get_or_insert(next),
                Some(_) => nodes[at].param.get_or_insert(next),
                None => nodes[at].literals.entry(segment.to_owned()).or_insert(next),
            };
            let child = *child;
            if child == next {
                nodes.push(Node::default());
            }
            at = child;
        }
        if nodes[at].ops.iter().any(|(m, _)| *m == op.method) {
            return Err(
                format!("two operations share {} {}", METHODS[op.method].0, op.path).into(),
            );
        }
        nodes[at].ops.push((op.method, index));
    }
    Ok(nodes)
}

fn params(path: &str) -> Vec<&str> {
    path.split('/')
        .filter_map(|s| s.strip_prefix('{').and_then(|s| s.strip_suffix('}')))
        .collect()
}

fn render(ops: &[Op], nodes: &[Node]) -> Result<String, Box<dyn Error>> {
    let index = |i: Option<usize>| i.map_or_else(|| "NONE".to_owned(), |i| i.to_string());
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by `cargo xtask gen` from {BUNDLE}. Do not edit."
    )?;
    writeln!(out)?;
    writeln!(out, "use crate::{{Method, Node, NONE, Operation}};")?;
    writeln!(out)?;
    writeln!(out, "pub static OPERATIONS: [Operation; {}] = [", ops.len())?;
    for op in ops {
        writeln!(
            out,
            "    Operation {{ id: {:?}, method: Method::{}, path: {:?}, params: &{:?}, category: {:?}, subcategory: {:?} }},",
            op.id,
            METHODS[op.method].1,
            op.path,
            params(&op.path),
            op.category,
            op.subcategory
        )?;
    }
    writeln!(out, "];")?;
    writeln!(out)?;
    writeln!(out, "pub static NODES: [Node; {}] = [", nodes.len())?;
    for node in nodes {
        let literals: Vec<String> = node
            .literals
            .iter()
            .map(|(s, i)| format!("({s:?}, {i})"))
            .collect();
        let node_ops: Vec<String> = node
            .ops
            .iter()
            .map(|(m, i)| format!("(Method::{}, {i})", METHODS[*m].1))
            .collect();
        writeln!(
            out,
            "    Node {{ literals: &[{}], param: {}, rest: {}, ops: &[{}] }},",
            literals.join(", "),
            index(node.param),
            index(node.rest),
            node_ops.join(", ")
        )?;
    }
    writeln!(out, "];")?;
    Ok(out)
}
